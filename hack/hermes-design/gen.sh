#!/usr/bin/env bash
# Generates the integratn-design Hermes skill ConfigMap from the files here.
#   hack/hermes-design/gen.sh            write the ConfigMap
#   hack/hermes-design/gen.sh --check    fail if it is out of date
# Edit SKILL.md, base.css or page.html, never the generated YAML.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../addons/cluster-roles/control-plane/addons/hermes/design-skill.yaml"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
python3 - "$here" > "$tmp" <<'PY'
import sys, pathlib
d = pathlib.Path(sys.argv[1])
print("# GENERATED by hack/hermes-design/gen.sh from hack/hermes-design/. Do not edit.")
print("# The integratn-design skill: James's design system for anything visual Hermes")
print("# makes. Mounted read-only under /opt/hermes-skills/homelab/integratn-design/")
print("# (see hermes-agent.yaml); the pod picks up changes on restart.")
print("apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: hermes-skill-design\n  namespace: hermes\ndata:")
for key in ("SKILL.md", "base.css", "page.html"):
    text = (d / key).read_text()
    assert "\t" not in text, f"{key}: tabs break YAML block scalars"
    print(f"  {key}: |")
    for line in text.rstrip("\n").split("\n"):
        print(("    " + line).rstrip())
PY
if [[ "${1:-}" == "--check" ]]; then
  diff -u "$out" "$tmp" && echo "design-skill.yaml is up to date"
else
  cp "$tmp" "$out"; echo "wrote $out"
fi
