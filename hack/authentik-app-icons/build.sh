#!/usr/bin/env bash
# Rebuild addons/clusters/the-cluster/addons/authentik/authentik-app-icons.yaml
# from icons/ here. One file per authentik application, named <slug>.<ext>;
# the blueprints point meta_icon at /static/dist/assets/images/apps/<file>.
# See README.md.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
out="$repo/addons/clusters/the-cluster/addons/authentik/authentik-app-icons.yaml"
python3 - "$here/icons" "$out" <<'PY'
import base64, pathlib, sys
src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
text, binary = [], []
for f in sorted(src.iterdir()):
    if f.suffix == ".svg":
        body = f.read_text().strip()
        text.append(f"  {f.name}: |\n" + "\n".join("    " + l if l else "" for l in body.splitlines()))
    elif f.suffix == ".png":
        binary.append(f"  {f.name}: {base64.b64encode(f.read_bytes()).decode()}")
head = """# GENERATED by hack/authentik-app-icons/build.sh -- edit icons/ there, not this file.
#
# Application icons for authentik's user library and admin list. Mounted into
# authentik-server at /web/dist/assets/images/apps (authentik/values.yaml), which
# the server serves as /static/dist/assets/images/apps/<file>. Served from
# authentik itself rather than hot-linked, so a sign-in page never makes a
# browser call a third-party host and an upstream moving a file breaks nothing.
apiVersion: v1
kind: ConfigMap
metadata:
  name: authentik-app-icons
  namespace: authentik
data:
"""
doc = head + "\n".join(text) + "\n"
if binary:
    doc += "binaryData:\n" + "\n".join(binary) + "\n"
out.write_text(doc)
PY
wc -c "$out"
