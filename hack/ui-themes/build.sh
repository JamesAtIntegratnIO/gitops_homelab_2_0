#!/usr/bin/env bash
# Rebuild the ArgoCD and Kargo brand stylesheets from the rule dumps and write
# them into the ConfigMap argocd-server serves them from. See README.md.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
out="$repo/addons/clusters/the-cluster/addons/argo-cd/manifests/argocd-styles-cm.yaml"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

gunzip -c "$here/argocd/rules.json.gz" > "$tmp/argocd.json"
gunzip -c "$here/kargo/rules.light.json.gz" > "$tmp/kargo-light.json"
gunzip -c "$here/kargo/rules.dark.json.gz" > "$tmp/kargo-dark.json"

{ cat "$here/argocd/base.css"
  echo "/* ---- generated by hack/ui-themes/gen.js from ArgoCD's own rules ---- */"
  node "$here/gen.js" "$here/argocd/map.js" "$tmp/argocd.json"; } > "$tmp/argocd.css"
{ cat "$here/kargo/base.css"
  node "$here/kargo/extras.js"
  echo "/* ---- generated by hack/ui-themes/gen.js from Kargo's own rules ---- */"
  node "$here/gen.js" "$here/kargo/map.js" "$tmp/kargo-light.json" "$tmp/kargo-dark.json"; } > "$tmp/kargo.css"

{ cat <<'HDR'
# GENERATED by hack/ui-themes/build.sh -- edit the sources there, not this file.
#
# IntegratnIO brand stylesheets for the ArgoCD and Kargo UIs. The argo-cd chart
# always mounts ConfigMap argocd-styles-cm (optional) at /shared/app/custom on
# argocd-server, which serves both files unauthenticated as static assets:
#   argocd.css -> loaded by ArgoCD itself via ui.cssurl
#   kargo.css  -> injected into Kargo's index.html by the gateway
#                 (kargo-extras/snippetsfilter.yaml)
apiVersion: v1
kind: ConfigMap
metadata:
  name: argocd-styles-cm
  namespace: argocd
data:
HDR
  for f in argocd kargo; do
    echo "  $f.css: |"
    sed 's/^/    /' "$tmp/$f.css"
  done; } > "$out"
wc -c "$tmp/argocd.css" "$tmp/kargo.css" "$out"
