#!/usr/bin/env node
// Writes the authentik brand manifests from the sources in this directory:
//   authentik-brand-assets.yaml      ConfigMap of SVGs, mounted into the server
//                                    at /web/dist/assets/images/integratn
//   authentik-blueprints-brand.yaml  ConfigMap holding the brand blueprint
//                                    (title, logo, favicon, CSS, backgrounds)
// Usage: node gen.js <output dir>
"use strict";
const fs = require("fs");
const path = require("path");
const s = require("./scenes");
const c = s.c;

const here = __dirname;
const out = process.argv[2];
if (!out) throw new Error("usage: gen.js <output dir>");

// Where the server serves the mounted ConfigMap: authentik's static backend
// passes any /static/... path straight through, and web/dist is /static/dist.
const STATIC = "/static/dist/assets/images/integratn";
const LABEL = "AUTH.CLUSTER.INTEGRATN.TECH";

// The mark is copied verbatim from integratn.io (IntegratnIO/integratn-io-astro
// public/favicon.svg and public/brand/integratn-mark.svg). The lockup is the
// site header's: mark, then "Integratn" in the system sans at 600.
const markBody = fs.readFileSync(path.join(here, "mark/integratn-mark.svg"), "utf8")
  .replace(/^[\s\S]*?<g /, "<g ").replace(/<\/svg>\s*$/, "").trim();
const lockup = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 236 48" width="236" height="48" role="img" aria-label="Integratn">
  <svg x="0" y="0" width="48" height="48" viewBox="-128 -128 256 256">${markBody}</svg>
  <text x="60" y="34" font-family="system-ui, -apple-system, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif" font-weight="600" font-size="31" letter-spacing="-0.6" fill="#f3f7fc">Integratn</text>
</svg>
`;

const scenes = {
  "bg-grid.svg": s.grid(),
  "bg-ridgeline.svg": s.ridgeline(),
  "bg-traces.svg": s.traces("OIDC", "AUTHORIZE"),
  "bg-sweep.svg": s.sweep(["the-cluster", "vcluster-media", "tower", "holocron", "pitdroid"]),
  "bg-hexdump.svg": s.hexdump("auth.integratn"),
  "bg-skyline.svg": s.skyline(),
};

const files = {
  "favicon.svg": fs.readFileSync(path.join(here, "mark/favicon.svg"), "utf8"),
  "logo.svg": lockup,
};
for (const [name, scene] of Object.entries(scenes)) files[name] = s.svg(scene, LABEL);

// Which flow wears which scene. The brand default (grid) covers every flow not
// listed, including ones added later.
const flows = {
  "default-authentication-flow": "bg-ridgeline.svg",
  "default-provider-authorization-implicit-consent": "bg-traces.svg",
  "default-provider-authorization-explicit-consent": "bg-traces.svg",
  "default-invalidation-flow": "bg-sweep.svg",
  "default-provider-invalidation-flow": "bg-sweep.svg",
  "default-source-authentication": "bg-skyline.svg",
  "default-source-enrollment": "bg-skyline.svg",
  "default-source-pre-authentication": "bg-skyline.svg",
  "default-password-change": "bg-hexdump.svg",
  "default-authenticator-totp-setup": "bg-hexdump.svg",
  "default-authenticator-webauthn-setup": "bg-hexdump.svg",
  "default-authenticator-static-setup": "bg-hexdump.svg",
};

const indent = (text, n) => text.replace(/\n$/, "").split("\n").map((l) => (l ? " ".repeat(n) + l : "")).join("\n");
const header = `# GENERATED by hack/authentik-theme/build.sh -- edit the sources there, not this file.\n`;

const assets = `${header}#
# IntegratnIO brand assets for authentik: the mark, the lockup and the flow
# backgrounds. Mounted into authentik-server at /web/dist/assets/images/integratn
# (authentik/values.yaml), which the server serves as ${STATIC}/.
apiVersion: v1
kind: ConfigMap
metadata:
  name: authentik-brand-assets
  namespace: authentik
data:
${Object.entries(files).map(([k, v]) => `  ${k}: |\n${indent(v, 4)}`).join("\n")}
`;

const css = fs.readFileSync(path.join(here, "brand.css"), "utf8");
const blueprint = `# authentik Blueprint: IntegratnIO brand
# Generated by hack/authentik-theme/build.sh. Styles the default brand and gives
# the default flows their backgrounds; the images are served from the
# authentik-brand-assets ConfigMap.
version: 1
metadata:
  name: integratn-brand
  labels:
    blueprints.goauthentik.io/instantiate: "true"
entries:
  # The default brand, whatever its domain. Only branding fields are set, so
  # its flows and certificates stay as they are.
  - model: authentik_brands.brand
    identifiers:
      default: true
    state: present
    attrs:
      branding_title: Integratn
      branding_logo: ${STATIC}/logo.svg
      branding_favicon: ${STATIC}/favicon.svg
      branding_default_flow_background: ${STATIC}/bg-grid.svg
      attributes:
        settings:
          theme:
            base: dark
            # The user interface ("My applications") draws this behind the
            # page instead of its two-tone slant.
            background: "background: ${c.ground} url('${STATIC}/bg-grid.svg') center / cover no-repeat;"
      branding_custom_css: |
${indent(css, 8)}
${Object.entries(flows).map(([slug, bg]) => `
  - model: authentik_flows.flow
    identifiers:
      slug: ${slug}
    state: present
    conditions:
      - !Find [authentik_flows.flow, [slug, ${slug}]]
    attrs:
      background: ${STATIC}/${bg}`).join("\n")}
`;

const blueprints = `${header}#
# Mounted by the chart (authentik/values.yaml blueprints.configMaps).
apiVersion: v1
kind: ConfigMap
metadata:
  name: authentik-blueprints-brand
  namespace: authentik
data:
  10-integratn-brand.yaml: |
${indent(blueprint, 4)}
`;

fs.writeFileSync(path.join(out, "authentik-brand-assets.yaml"), assets);
fs.writeFileSync(path.join(out, "authentik-blueprints-brand.yaml"), blueprints);
// Raw files too, for previewing without a cluster.
if (process.env.RAW) {
  fs.mkdirSync(process.env.RAW, { recursive: true });
  for (const [k, v] of Object.entries(files)) fs.writeFileSync(path.join(process.env.RAW, k), v);
  fs.writeFileSync(path.join(process.env.RAW, "10-integratn-brand.yaml"), blueprint);
}
